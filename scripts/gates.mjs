// Creative gates. Run: npm run gates (also runs before every build).
// Checks what a script can check from docs/BUILD-GUIDE.md. A failure stops the build.
import { readFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const walk = (dir) => readdirSync(dir).flatMap((f) => { const p = join(dir, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
const files = walk(join(root, "app")).filter((f) => /\.(tsx?|css)$/.test(f));
const fails = [];
const fail = (file, line, msg) => fails.push(`${relative(root, file)}:${line}  ${msg}`);

// 1. Words that make copy sound like every other agency.
const banned = [
  "elevate", "unlock", "seamless", "revolutioni[sz]e", "cutting[- ]edge", "world[- ]class", "game[- ]chang", "leverag", "synerg",
  "next level", "in today's", "delve", "tapestry", "supercharge", "empower", "robust", "bespoke solution", "passionate about",
  "best[- ]in[- ]class", "one[- ]stop shop", "take your .{0,20} to new heights", "award[- ]winning",
];
const bannedRx = new RegExp(`\\b(${banned.join("|")})`, "i");
// 2. Work is labeled by who commissioned it, never by the tool that made it.
const toolRx = /\b(AI[- ]generated|AI[- ]made|AI[- ]assisted|made with AI|AI performers?|AI concepts?|AI people|generated by AI)\b/i;
// 3. Slop tells in copy and markup.
const emojiRx = /[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}]/u;
const loremRx = /lorem ipsum|placeholder text|coming soon/i;
const slopCss = /(from|via|to)-(purple|violet|indigo|fuchsia)-\d{3}|backdrop-blur-(md|lg|xl|2xl|3xl)|blur-3xl/;

// Other people's words are theirs to keep: a client site's own headline (described in an alt text), anything inside curly quotes
// (real messages on the Proof page), and the signature dash on a strip of wall tape.
const allow = [/Elevate Your TikTok LIVE Career/, /“[^”]*”/g, /className="gt-sign">— /];

for (const f of files) {
  const isCopy = /\.(tsx?)$/.test(f);
  const all = readFileSync(f, "utf8").split("\n");
  all.forEach((raw, i) => {
    let line = raw;
    for (const a of allow) line = line.replace(a, "");
    if (/^\s*(\/\/|\*|\/\*)/.test(line) && !toolRx.test(line)) return; // code comments may say anything except tool labels
    const n = i + 1;
    if (isCopy) {
      const strings = [...line.matchAll(/"([^"\n]{12,})"|>([^<>{}\n]{12,})</g)].map((m) => m[1] ?? m[2]).filter((s) => /\s/.test(s) && !/^[\w\-\[\]:./()%,#!&*+ ]+$/.test(s) || /[a-z] [a-z]+ [a-z]/.test(s ?? ""));
      for (const s of strings) {
        if (/className|^\s*[\w-]+(\s[\w\-\[\]:./()%,#!&*+]+)+\s*$/.test(s) && !/[.?,'’]\s|[.?]$/.test(s)) continue; // class lists
        const b = s.match(bannedRx); if (b) fail(f, n, `banned word "${b[0]}"`);
        if (s.includes("—")) fail(f, n, "em dash in copy");
        if (/[a-z]!(\s|$)/.test(s) && !/^import|!text-|!\[|!==|!whitespace|!leading/.test(s)) fail(f, n, "exclamation mark in copy");
        if (loremRx.test(s)) fail(f, n, "placeholder copy");
      }
      if (emojiRx.test(line)) fail(f, n, "emoji");
    }
    const t = line.match(toolRx); if (t) fail(f, n, `work labeled by tool: "${t[0]}"`);
    const c = line.match(slopCss); if (c) fail(f, n, `slop styling "${c[0]}"`);
    const px = line.match(/text-\[(\d+)px\]/g); if (px) for (const p of px) if (Number(p.match(/\d+/)[0]) < 12) fail(f, n, `text under 12px (${p})`);
    if (/<Image\b/.test(line) && !/\balt\b/.test(all.slice(i, i + 10).join(" "))) fail(f, n, "image without alt");
  });
}

// 4. The offer: every scene complete, nothing shared between pages, every proof real.
const offer = readFileSync(join(root, "app/content/offer.ts"), "utf8");
const work = readFileSync(join(root, "app/content/work.ts"), "utf8");
const caseSlugs = new Set([...work.matchAll(/^    slug: "([^"]+)"/gm)].map((m) => m[1]));
const blocks = offer.split(/\n  \{\n    slug: "/).slice(1);
const seen = new Map();
const one = (b, key) => b.match(new RegExp(`\\n    ${key}: "((?:[^"\\\\]|\\\\.)*)"`))?.[1] ?? "";
for (const b of blocks) {
  const slug = b.slice(0, b.indexOf('"'));
  const where = `app/content/offer.ts (${slug})`;
  for (const key of ["name", "line", "answer"]) {
    const v = one(b, key);
    if (!v) fails.push(`${where}  missing ${key}`);
    const k = `${key}:${v.toLowerCase()}`;
    if (key !== "name" && seen.has(k)) fails.push(`${where}  ${key} is the same as ${seen.get(k)}`);
    seen.set(k, slug);
  }
  const answer = one(b, "answer");
  if (answer && (answer.length < 70 || answer.length > 260)) fails.push(`${where}  answer should be one sentence of 70 to 260 characters (${answer.length})`);
  if (answer && !/ is /.test(answer)) fails.push(`${where}  answer must define the service ("X is ...")`);
  const faq = (b.match(/\{ q: "/g) || []).length;
  if (faq < 2) fails.push(`${where}  needs at least 2 questions (${faq})`);
  const get = b.match(/\n    get: \[(.*)\],/)?.[1].match(/"(?:[^"\\]|\\.)*"/g) || [];
  if (get.length < 4) fails.push(`${where}  needs at least 4 deliverables (${get.length})`);
  const proof = b.match(/\n    proof: \[(.*)\],/)?.[1].match(/"([^"]+)"/g)?.map((s) => s.slice(1, -1)) || [];
  if (!proof.length) fails.push(`${where}  needs at least one proof case`);
  for (const p of proof) if (!caseSlugs.has(p)) fails.push(`${where}  proof "${p}" is not a case in work.ts`);
  const title = b.match(/meta: \{ title: "([^"]+)", description: "([^"]+)"/);
  if (!title) fails.push(`${where}  missing meta`);
  else {
    if (title[1].length > 62) fails.push(`${where}  meta title over 62 characters (${title[1].length})`);
    if (title[2].length < 110 || title[2].length > 165) fails.push(`${where}  meta description should be 110 to 165 characters (${title[2].length})`);
  }
  for (const para of b.match(/"(?:[^"\\]|\\.){90,}"/g) || []) {
    const k = `p:${para}`;
    if (seen.has(k)) fails.push(`${where}  shares a paragraph with ${seen.get(k)}`);
    seen.set(k, slug);
  }
}
if (blocks.length !== 14) fails.push(`app/content/offer.ts  expected 14 scenes, found ${blocks.length}`);

// 5. Every local image a page points at exists.
for (const f of files.filter((x) => /\.tsx?$/.test(x))) {
  readFileSync(f, "utf8").split("\n").forEach((line, i) => {
    for (const m of line.matchAll(/"(\/(?:work|media)\/[\w\-./]+\.(?:webp|png|jpg|jpeg|avif|mp4|svg))"/g)) {
      if (!existsSync(join(root, "public", m[1]))) fail(f, i + 1, `missing file ${m[1]}`);
    }
  });
}

if (fails.length) {
  console.error(`\nCreative gates: ${fails.length} problem${fails.length === 1 ? "" : "s"}\n`);
  for (const x of fails) console.error("  " + x);
  console.error("\nSee docs/BUILD-GUIDE.md. Fix these before the build.\n");
  process.exit(1);
}
console.log(`Creative gates: all clear (${files.length} files, ${blocks.length} scenes).`);
